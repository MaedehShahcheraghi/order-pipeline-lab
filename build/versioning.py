#!/usr/bin/env python3
"""GitFlow version calculator with durable release-cut anchors.

State sources, all audit-able in Git:
 * stable tags: vX.Y.Z (only after successful GHCR promotion)
 * dev/rc tags: vX.Y.Z-dev.N / vX.Y.Z-rc.N
 * immutable release cuts: cut/vX.Y.Z, pointing to the cut SHA on develop

This script NEVER pushes/changes refs. CI owns publication and ref creation.
Version bump policy: breaking > feature > fix > none. Commits from a
previous release/hotfix are forward-ported with a `sync:` MR title; their
changes are excluded from the *new* version bump by the release-cut boundary
and the sync classification. Every successful new target build increments N.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

STABLE = re.compile(r"^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$")
DEV = re.compile(r"^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)-dev\.([1-9]\d*)$")
RC = re.compile(r"^v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)-rc\.([1-9]\d*)$")
CUT = re.compile(r"^cut/v(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$")
BRANCH = re.compile(r"^(release|hotfix)/(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$")
CC = re.compile(r"^([a-z][\w-]*)(?:\(([^)]+)\))?(!)?:\s+(.+)$")
WEIGHT = {"none": 0, "fix": 1, "feat": 2, "breaking": 3}


@dataclass(frozen=True, order=True)
class Version:
    major: int
    minor: int
    patch: int

    def __str__(self) -> str:
        return f"{self.major}.{self.minor}.{self.patch}"


def git(*args: str) -> str:
    return subprocess.check_output(["git", *args], text=True, stderr=subprocess.PIPE).strip()


def ancestor(old: str, new: str) -> bool:
    return subprocess.run(["git", "merge-base", "--is-ancestor", old, new],
                          capture_output=True, check=False).returncode == 0


def tagmap() -> dict[str, str]:
    """Tag name -> commit (dereference annotated tags)."""
    lines = git("for-each-ref", "--format=%(refname:short)", "refs/tags").splitlines()
    return {name: git("rev-parse", f"refs/tags/{name}^{{commit}}") for name in lines}


def parse_version(pattern: re.Pattern[str], name: str) -> Version | None:
    m = pattern.fullmatch(name)
    return Version(*map(int, m.groups()[:3])) if m else None


def latest_stable(tags: dict[str, str]) -> tuple[Version, str | None]:
    pairs = [(v, name) for name in tags if (v := parse_version(STABLE, name))]
    return max(pairs, default=(Version(0, 0, 0), None))


def bump(base: Version, kind: str) -> Version:
    if kind == "breaking":
        return Version(base.major + 1, 0, 0)
    if kind == "feat":
        return Version(base.major, base.minor + 1, 0)
    if kind == "fix":
        return Version(base.major, base.minor, base.patch + 1)
    if kind == "none":
        return base
    raise ValueError(f"Unknown change kind: {kind}")


def change_type(message: str) -> str:
    """Read *PR title*, not the GitHub autogenerated Merge pull request subject.

    All merge-message inner lines are inspected, but only conventional titles,
    not arbitrary text, can increase the level. `sync:` is deliberately none.
    Breaking footer is honored for normal commits and merge bodies.
    """
    if re.search(r"(?mi)^BREAKING[ -]CHANGE:\s*\S", message):
        return "breaking"
    lines = [x.strip() for x in message.splitlines() if x.strip()]
    if not lines:
        return "none"
    candidates = lines[1:] if lines[0].startswith(("Merge pull request #", "Merge branch '")) else lines[:1]
    best = "none"
    for line in candidates:
        m = CC.fullmatch(line)
        if not m:
            continue
        verb, _, bang, _ = m.groups()
        new = "breaking" if bang else "feat" if verb == "feat" else "fix" if verb in ("fix", "perf") else "none"
        if WEIGHT[new] > WEIGHT[best]:
            best = new
    return best


def first_parent(sha: str) -> list[str]:
    return git("rev-list", "--first-parent", sha).splitlines()


def strongest_changes(sha: str, boundary: str | None) -> str:
    """Only commits after boundary on develop's first-parent path are changes.

    GitHub squash/merge PR policy is essential. Forward-port MR titles `sync:`
    are not interpreted as new product work. A normal fix/feat on develop after
    a cut is independent new work and counts towards the NEXT release.
    """
    path = first_parent(sha)
    if boundary:
        if boundary not in path:
            raise ValueError("Release-cut / baseline must be on develop first-parent history")
        path = path[:path.index(boundary)]
    result = "none"
    for commit in path:
        kind = change_type(git("show", "-s", "--format=%B", commit))
        if WEIGHT[kind] > WEIGHT[result]:
            result = kind
    return result


def nearest_cut(tags: dict[str, str], sha: str) -> tuple[Version, str] | None:
    commits = first_parent(sha)
    cuts: dict[str, Version] = {}
    for name, commit in tags.items():
        if (v := parse_version(CUT, name)):
            if commit in cuts and cuts[commit] != v:
                raise ValueError("Two different release cuts refer to the same commit")
            cuts[commit] = v
    for commit in commits:
        if commit in cuts:
            return cuts[commit], commit
    return None


def nearest_dev(tags: dict[str, str], sha: str, boundary: str | None) -> tuple[Version, int] | None:
    refs: dict[str, list[tuple[Version, int]]] = {}
    for name, commit in tags.items():
        if (match := DEV.fullmatch(name)):
            numbers = list(map(int, match.groups()))
            refs.setdefault(commit, []).append((Version(*numbers[:3]), numbers[3]))
    for commit in first_parent(sha):
        if boundary and commit == boundary:
            break  # A dev tag AT the release cut belongs to the previous cycle.
        if commit in refs:
            return max(refs[commit])
    return None


def tag_on_sha(tags: dict[str, str], pattern: re.Pattern[str], sha: str) -> str | None:
    matches = [name for name, commit in tags.items() if commit == sha and pattern.fullmatch(name)]
    if len(matches) > 1:
        raise ValueError(f"Ambiguous version tags for commit {sha}: {matches}")
    return matches[0] if matches else None


def boundary_before_first_cut(tags: dict[str, str], sha: str) -> str | None:
    """For the original cycle, use stable SHA if on first-parent; otherwise
    use the merge base only if it is on first-parent. Never subtract unrelated
    commits by using an arbitrary latest stable without a history boundary.
    """
    stable, tag = latest_stable(tags)
    if tag is None:
        return None
    stable_sha = tags[tag]
    mb = git("merge-base", sha, stable_sha)
    if mb not in first_parent(sha):
        raise ValueError("Stable baseline is not on develop first-parent; create a release cut or sync baseline")
    return mb


@dataclass(frozen=True)
class Result:
    tag: str
    version: str
    is_new: bool
    sha: str
    kind: str
    source_rc: str = ""
    boundary: str = ""
    reason: str = ""


def calculate(kind: str, branch: str, sha: str, tags: dict[str, str] | None = None) -> Result:
    all_tags = tagmap() if tags is None else tags
    stable, _ = latest_stable(all_tags)
    short = sha[:12]
    if kind == "dev":
        if branch != "develop":
            raise ValueError("Dev versions may only be built on develop")
        existing = tag_on_sha(all_tags, DEV, sha)
        if existing:
            # Earlier tags are immutable, even if a newer Stable has appeared.
            return Result(existing, existing[1:], False, sha, kind, reason="already tagged")
        cut = nearest_cut(all_tags, sha)
        base, boundary = cut if cut else (stable, boundary_before_first_cut(all_tags, sha))
        change = strongest_changes(sha, boundary)
        previous = nearest_dev(all_tags, sha, boundary)
        # Reserve the cut version; if hotfix published the same target, advance.
        candidate = max(bump(base, change), bump(stable, change)) if change != "none" else base
        if previous and previous[0] > stable:
            candidate = max(candidate, previous[0])
        if candidate <= stable or (cut and candidate <= cut[0]):
            # No independent work for the next release yet. Still publish a SHA
            # artifact for CI traceability, but do NOT create a SemVer tag.
            return Result("", f"sha-{short}", False, sha, kind, boundary=boundary or "", reason="no releasable changes")
        number = previous[1] + 1 if previous and previous[0] == candidate else 1
        tag = f"v{candidate}-dev.{number}"
        if tag in all_tags:
            raise ValueError(f"Tag collision: {tag} already exists; fetch tags or serialize publish jobs")
        return Result(tag, tag[1:], True, sha, kind, boundary=boundary or "", reason=f"{change} after cut/baseline")

    m = BRANCH.fullmatch(branch)
    if not m:
        raise ValueError("Release/hotfix branch must be release/X.Y.Z or hotfix/X.Y.Z")
    source_type, *numbers = m.groups()
    target = Version(*map(int, numbers))
    if kind == "rc":
        if source_type == "release":
            cut_ref = f"cut/v{target}"
            if cut_ref not in all_tags or not ancestor(all_tags[cut_ref], sha):
                raise ValueError(f"Release requires a valid {cut_ref} ancestor; use automatic Prepare Release")
        else:
            if f"cut/v{target}" in all_tags:
                raise ValueError(f"Hotfix {target} conflicts with an existing release cut")
            stable_sha = all_tags.get(f"v{stable}")
            if stable_sha and git("rev-parse", f"{stable_sha}^{{tree}}") == git("rev-parse", f"{sha}^{{tree}}"):
                return Result("", f"sha-{short}", False, sha, kind, reason="awaiting hotfix commit")
        existing = tag_on_sha(all_tags, RC, sha)
        if existing:
            if parse_version(RC, existing) != target:
                raise ValueError("Commit has RC for another version")
            return Result(existing, existing[1:], False, sha, kind, reason="already tagged")
        if target <= stable:
            raise ValueError(f"Cannot publish RC {target}; latest Stable is {stable}")
        suffixes = [int(m.group(4)) for name in all_tags if (m := RC.fullmatch(name)) and
                    Version(*map(int, m.groups()[:3])) == target]
        tag = f"v{target}-rc.{max(suffixes, default=0) + 1}"
        return Result(tag, tag[1:], True, sha, kind)

    if kind == "stable":
        tag = f"v{target}"
        if tag in all_tags:
            if all_tags[tag] != sha:
                raise ValueError(f"Stable tag {tag} exists on a different commit")
            return Result(tag, str(target), False, sha, kind, reason="already released")
        if target <= stable:
            raise ValueError(f"Stable version {target} must exceed latest Stable {stable}")
        rcs = [(int(m.group(4)), name) for name in all_tags
               if (m := RC.fullmatch(name)) and Version(*map(int, m.groups()[:3])) == target]
        if not rcs:
            raise ValueError("Final release requires a successfully published RC, including hotfixes")
        rc = max(rcs)[1]
        rc_commit = all_tags[rc]
        if not ancestor(rc_commit, sha):
            raise ValueError("Latest RC must be ancestor of main merge commit; do NOT squash release/hotfix MR")
        # Prohibit untested tree changes after RC; support build-once/promote.
        if git("rev-parse", f"{rc_commit}^{{tree}}") != git("rev-parse", f"{sha}^{{tree}}"):
            raise ValueError("Main tree differs from approved RC; create/test a new RC before stable release")
        return Result(tag, str(target), True, sha, kind, source_rc=rc, reason="promote exact RC image")
    raise ValueError(f"Invalid kind {kind}")


def prepare(mode: str, sha: str, tags: dict[str, str] | None = None) -> tuple[str, str, str]:
    """Choose new branch and cut tag. Does not mutate Git; CI checks refs & pushes."""
    all_tags = tagmap() if tags is None else tags
    latest, stable_tag = latest_stable(all_tags)
    if mode == "release":
        dev = tag_on_sha(all_tags, DEV, sha)
        if not dev:
            raise ValueError("Release Cut requires a green, tagged develop commit (dev.N)")
        target = parse_version(DEV, dev)
        if target is None or target <= latest:
            raise ValueError("Current develop tag does not target a newer version than Stable")
        cut = f"cut/v{target}"
        if cut in all_tags:
            raise ValueError(f"Release cut already exists: {cut}")
        return f"release/{target}", cut, sha
    if mode == "hotfix":
        if not stable_tag:
            raise ValueError("Hotfix requires an existing published Stable tag")
        target = bump(latest, "fix")
        if any(parse_version(RC, x) == target or parse_version(CUT, x) == target for x in all_tags):
            raise ValueError(f"Version {target} reserved by a release; resolve version conflict before hotfix")
        return f"hotfix/{target}", "", all_tags[stable_tag]
    raise ValueError(f"Invalid prepare mode {mode}")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--kind", required=True, choices=["dev", "rc", "stable", "prepare-release", "prepare-hotfix"])
    p.add_argument("--branch", default="")
    p.add_argument("--sha", default="HEAD")
    a = p.parse_args()
    sha = git("rev-parse", f"{a.sha}^{{commit}}")
    if a.kind.startswith("prepare-"):
        branch, cut, base_sha = prepare(a.kind.removeprefix("prepare-"), sha)
        outputs = {"branch": branch, "cut_tag": cut, "sha": base_sha, "base_sha": base_sha}
    else:
        if git("rev-parse", "HEAD") != sha:
            raise ValueError("Checkout must be at exact commit being published")
        r = calculate(a.kind, a.branch, sha)
        outputs = {"tag": r.tag, "version": r.version, "new": str(r.is_new).lower(),
                   "sha": r.sha, "short_sha": r.sha[:12], "source_rc": r.source_rc,
                   "reason": r.reason, "boundary": r.boundary}
    for name, value in outputs.items():
        print(f"{name}={value}")
    if path := os.getenv("GITHUB_OUTPUT"):
        with Path(path).open("a", encoding="utf-8") as f:
            for name, value in outputs.items():
                f.write(f"{name}={value}\n")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, subprocess.CalledProcessError) as e:
        print(f"VERSIONING ERROR: {e}", file=sys.stderr)
        sys.exit(1)
